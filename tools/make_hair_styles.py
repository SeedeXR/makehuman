# Cornrows.
#
# Rows are PATHS over the scalp, not stripes painted on a shell. The base mesh
# cannot carry them as offsets on its own vertices: MEASURED, the hair-bearing
# scalp is 1.504 dm wide with a median edge of 0.1436 dm, about ten vertices
# across, so ridge/gap/ridge allows at most five rows one vertex wide -- a
# corrugated cap. So the geometry is AUTHORED here and bound to the scalp by
# `--bind-points`, which is what the barycentric binder exists for.

import subprocess

APP_ENV = "MH_APP"


def app_binary(override: str = "") -> str:
    """The built application, which owns the scalp walk and the binder.

    Shelling out rather than reimplementing: a second Dijkstra and a second
    barycentric solver in Python would drift from the ones the application
    actually uses, and the drift would show as hair that sits right in the
    generator and wrong in the app.
    """
    import os
    # Passed down from `main(--app)` rather than kept in a module global: the
    # global needed a suppression comment to excuse it, and the comment was not
    # even valid suppression syntax (`python:S7632`).
    override = override or os.environ.get(APP_ENV)
    if override:
        return override
    return str(ROOT / "build" / "macos-arm64-debug" / "src" / "app" / "makehuman.app" /
               "Contents" / "MacOS" / "makehuman")


def bind_points(app: str, points) -> list[str]:
    """Hand the authored points to the application's barycentric binder.

    The scratch file goes to a TEMPORARY directory, not to `build/`. It used to
    be `ROOT/build/cornrow_points.txt`, which had two faults: `--check` is a
    read-only gate and should not write into the source tree at all, and on a
    checkout never configured in-source `build/` does not exist, so the write
    raised `FileNotFoundError` -- which `main()` then reported as "cannot derive
    the hair styles without the application" while the application was fine.
    """
    import tempfile
    with tempfile.TemporaryDirectory() as d:
        tmp = Path(d) / "points.txt"
        tmp.write_text("".join(f"{x:.6f} {y:.6f} {z:.6f}\n" for x, y, z in points))
        out = subprocess.run([app, "--bind-points", str(tmp)],
                             capture_output=True, text=True, check=True).stdout
    return [line for line in out.splitlines() if line.strip()]


# Rows are placed across the crown's width, not the region's; see
# `crown_half_width`. Elevation, in degrees about the cranium centre.
CROWN_ELEVATION = 40.0


def region_triangles(verts, region, body_faces):
    """The region's own triangles, and an outward normal per triangle.

    The filter is per SPLIT TRIANGLE, not per quad, because that is what
    `bindToSurface` does (`src/core/SurfaceBind.cpp:102-112`): it splits first
    and then drops a triangle only if one of ITS three corners is outside the
    region. Filtering per quad was a real difference, not a nicety -- a review
    measured 408 triangles here against the binder's 414, and two of the six
    triangles only the binder saw carry cornrow bindings. Since `max_dist`
    decides where each row ENDS, the rows were being cut against a surface a
    triangle-ring smaller than the one they are actually bound to.
    """
    rs = set(region)
    tris = []
    for f in body_faces:
        for k in range(1, len(f) - 1):
            corners = (f[0], f[k], f[k + 1])
            if not all(v in rs for v in corners):
                continue
            a, b, c = (verts[v] for v in corners)
            u = [b[i] - a[i] for i in range(3)]
            w = [c[i] - a[i] for i in range(3)]
            n = [u[1] * w[2] - u[2] * w[1], u[2] * w[0] - u[0] * w[2],
                 u[0] * w[1] - u[1] * w[0]]
            ln = math.sqrt(sum(t * t for t in n)) or 1.0
            n = [t / ln for t in n]
            mid = [(a[i] + b[i] + c[i]) / 3.0 - CENTRE[i] for i in range(3)]
            if sum(n[i] * mid[i] for i in range(3)) < 0.0:
                n = [-t for t in n]
            tris.append((a, b, c, n))
    return tris


def crown_half_width(verts, region):
    """How far off the midline a row may sit, measured on the crown.

    The region's FULL half-width (0.7521) is the wrong number and using it cost
    two rounds here: it is reached down at ear height, so a row placed there has
    no scalp above it to arc over and the trace finds nothing. MEASURED on the
    shipped mesh, the region narrows with elevation -- 0.6326 above 30 degrees,
    0.5444 above 40, 0.4362 above 50 -- and the widest row has to clear the
    crown, not the temple.
    """
    return max(abs(verts[v][0] - CENTRE[0]) for v in region
               if spherical(verts[v])[0] > CROWN_ELEVATION)


def _along(base, edge, num, den):
    """A point along `edge` from `base`, the degenerate denominator guarded.

    `closestBarycentric` (`src/core/SurfaceBind.cpp:31-74`) guards all four of
    its divisions; the first cut of this port dropped every one. The base mesh
    happens to have no zero-area body triangle today (smallest 5.5e-6), so it
    was latent rather than harmless.

    `if den` rather than `den != 0.0`: an exact float compare trips
    `python:S1244`, and the truthiness form is what the other call sites here
    already use.
    """
    t = num / den if den else 0.0
    return [base[i] + edge[i] * t for i in range(3)]


def _closest_past_ab(p, a, b, c, ab, ac, dots):
    """The half of Ericson's test that needs the third corner's products.

    Split out of `closest_on_triangle` for one reason: together they score 19
    against Sonar's cognitive-complexity limit of 15 (`python:S3776`). The ORDER
    of the tests is deliberately unchanged -- they are Voronoi regions and the
    C++ reference interleaves them exactly this way, so reordering could return
    a different (equally close) point at a tie and silently move the asset.
    """
    d1, d2, d3, d4 = dots
    cp = [p[i] - c[i] for i in range(3)]
    d5 = sum(ab[i] * cp[i] for i in range(3))
    d6 = sum(ac[i] * cp[i] for i in range(3))
    if d6 >= 0.0 and d5 <= d6:
        return c
    vb = d5 * d2 - d1 * d6
    if vb <= 0.0 and d2 >= 0.0 and d6 <= 0.0:
        return _along(a, ac, d2, d2 - d6)
    va = d3 * d6 - d5 * d4
    if va <= 0.0 and (d4 - d3) >= 0.0 and (d5 - d6) >= 0.0:
        bc = [c[i] - b[i] for i in range(3)]
        return _along(b, bc, d4 - d3, (d4 - d3) + (d5 - d6))
    vc = d1 * d4 - d3 * d2
    denom = va + vb + vc
    if not denom:
        return a
    v, w = vb / denom, vc / denom
    return [a[i] + ab[i] * v + ac[i] * w for i in range(3)]


def closest_on_triangle(p, a, b, c):
    """Ericson's closest point on a triangle -- the one `bindToSurface` uses."""
    ab = [b[i] - a[i] for i in range(3)]
    ac = [c[i] - a[i] for i in range(3)]
    ap = [p[i] - a[i] for i in range(3)]
    d1 = sum(ab[i] * ap[i] for i in range(3))
    d2 = sum(ac[i] * ap[i] for i in range(3))
    if d1 <= 0.0 and d2 <= 0.0:
        return a
    bp = [p[i] - b[i] for i in range(3)]
    d3 = sum(ab[i] * bp[i] for i in range(3))
    d4 = sum(ac[i] * bp[i] for i in range(3))
    if d3 >= 0.0 and d4 <= d3:
        return b
    vc = d1 * d4 - d3 * d2
    if vc <= 0.0 and d1 >= 0.0 and d3 <= 0.0:
        return _along(a, ab, d1, d1 - d3)
    return _closest_past_ab(p, a, b, c, ab, ac, (d1, d2, d3, d4))


def project_to_region(p, tris):
    """The closest point on the region, its triangle's normal, and the distance.

    Exhaustive over the region's 408 triangles. An acceleration structure would
    be the third thing here that is faster and wrong: the earlier
    raycast-from-the-centre placement had a nearest-direction FALLBACK that
    silently collapsed every missed ray onto the scalp rim.
    """
    best, bestn, bestd = None, None, float("inf")
    for a, b, c, n in tris:
        q = closest_on_triangle(p, a, b, c)
        d = math.dist(p, q)
        if d < bestd:
            best, bestn, bestd = q, n, d
    return best, bestn, bestd


def trace_row(tris, x, t0=0.0, t1=250.0, samples=70, max_dist=0.04):
    """One row: the scalp's cross-section at x, traced front-to-nape.

    `t` is the angle about the cranium centre in the sagittal plane -- 0 dead
    front, 90 the crown, 180 dead back -- and it is swept MONOTONICALLY. That
    monotonicity is the whole point, and it is the third routing tried here:

      * Walking base vertices gave a MEASURED max turn of 106 degrees. No
        vertex-picking rule can be smoother than the 0.1436 dm mesh it picks
        from.
      * A fixed ellipsoid about the cranium centre is smooth but does not fit
        the occiput: MEASURED, its tail stands 0.25 dm off the surface by
        elevation -45, and projecting those samples collapses them onto the
        region's RIM -- rows stopped 15 to 37 degrees above the hairline at the
        back and left the occiput bare.
      * Marching freely over the surface tracks the occiput but can REVERSE:
        the new direction came from the projected displacement, which snaps
        sideways at a facet, and two rows turned round and went back over the
        crown (max turn 79 degrees).

    So the angle advances on its own and only the RADIUS is carried forward
    from the previous projected point. The head's radius varies slowly, so each
    candidate starts near the surface and the projection is a small correction
    rather than a search -- smooth by construction, and it cannot double back.

    `samples` is a real trade-off, not a free parameter: finer steps amplify
    per-facet jitter into the turn angle. MEASURED over the six rows, the max
    turn between PATH POINTS runs 14.6..21.9 degrees at 40 samples, 17.7..19.8
    at 70 and 19.0..28.9 at 90, while the largest gap between samples falls from
    0.124 dm to 0.070 and then 0.055. 70 is where the rows are smoothest.

    Those are turns between path points. `test_cornrows_shape.cpp` measures
    between RING CENTROIDS and gets larger numbers for the same geometry, for
    the reason stated there -- the two are not comparable and neither is wrong.
    """
    out, r = [], None
    for i in range(samples):
        t = math.radians(t0 + (t1 - t0) * i / (samples - 1))
        if r is None:
            # Settle the first radius before the sweep starts, so the first
            # sample is no worse placed than the rest.
            r = 0.8
            for _ in range(6):
                q, _n, _d = project_to_region(
                    [x, CENTRE[1] + r * math.sin(t), CENTRE[2] + r * math.cos(t)], tris)
                r = math.hypot(q[1] - CENTRE[1], q[2] - CENTRE[2])
        q, nrm, d = project_to_region(
            [x, CENTRE[1] + r * math.sin(t), CENTRE[2] + r * math.cos(t)], tris)
        if d > max_dist:
            # Before the row has started this is the forehead, above the
            # hairline; after it has started it is the rim, and the row is done.
            if out:
                break
            continue
        r = math.hypot(q[1] - CENTRE[1], q[2] - CENTRE[2])
        out.append((q, nrm, d))
    return out


def ridge(path, stand=0.13, half=0.06, sides=6):
    """A rounded ridge swept along one path: the braid itself.

    The frame is the path TANGENT and the true SURFACE NORMAL. A first version
    used the radial direction from the cranium centre and rendering it settled
    the matter: radial is nearly TANGENTIAL where the scalp curves away at
    front and back, so the ring lay flat in the surface and vanished, leaving
    six short spikes at the crown. Radial only behaves like a normal on a
    sphere.

    The ring is pushed fully clear of the skin (`0.55 + 0.45*cos`), because a
    section centred on the surface buries half of itself in the head.
    """
    pts = [p for p, _n, _d in path]
    normals = [n for _p, n, _d in path]
    out, rings = [], []
    for i, p in enumerate(pts):
        nxt = pts[min(i + 1, len(pts) - 1)]
        prv = pts[max(i - 1, 0)]
        t = [nxt[k] - prv[k] for k in range(3)]
        tl = math.sqrt(sum(c * c for c in t)) or 1.0
        t = [c / tl for c in t]
        outward = normals[i]
        side = [t[1] * outward[2] - t[2] * outward[1],
                t[2] * outward[0] - t[0] * outward[2],
                t[0] * outward[1] - t[1] * outward[0]]
        sl = math.sqrt(sum(c * c for c in side)) or 1.0
        side = [c / sl for c in side]
        ring = []
        for k in range(sides):
            a = 2.0 * math.pi * k / sides
            r = [p[j] + outward[j] * (stand * (0.55 + 0.45 * math.cos(a)))
                 + side[j] * (half * math.sin(a)) for j in range(3)]
            ring.append(len(out))
            out.append(tuple(r))
        rings.append(ring)
    faces = []
    for i in range(len(rings) - 1):
        for k in range(sides):
            a, b = rings[i][k], rings[i][(k + 1) % sides]
            c, d = rings[i + 1][(k + 1) % sides], rings[i + 1][k]
            faces.append([a, b, c, d])
    return out, faces


CORNROW_ROWS = 6


def cornrows(verts, body_faces, app_path=""):
    """Six rows: the scalp's cross-section at six lateral offsets, each swept.

    Every step is its own function deliberately. The previous `cornrows()`
    scored about 14 against Sonar's cognitive-complexity limit of 15
    (`python:S3776`), so growing it by even one branch fails the gate.
    """
    app = app_binary(app_path)
    # The region comes from the APPLICATION, which owns the definition
    # (`mh::core::hairBearingScalp`). Deriving it here again would be a third
    # copy of the hairline, free to drift from the other two.
    region = [int(line.split()[0])
              for line in subprocess.run([app, "--spread-roots", "999"],
                                         capture_output=True, text=True,
                                         check=True).stdout.splitlines()
              if line.strip()]
    if len(region) < CORNROW_ROWS:
        raise RuntimeError(f"the application returned {len(region)} scalp vertices")
    tris = region_triangles(verts, region, body_faces)
    if not tris:
        raise RuntimeError("no triangle lies wholly inside the scalp region")
    half = crown_half_width(verts, region)

    allpts, allfaces, traced = [], [], 0
    for i in range(CORNROW_ROWS):
        u = (2.0 * i + 1.0) / CORNROW_ROWS - 1.0
        path = trace_row(tris, CENTRE[0] + half * u)
        if len(path) < 3:
            print(f"cornrows: row {i} traced {len(path)} samples -- dropped", file=sys.stderr)
            continue
        pts, fs = ridge(path)
        base = len(allpts)
        allpts.extend(pts)
        allfaces.extend([[k + base for k in f] for f in fs])
        traced += 1
    return allpts, allfaces, traced, app


