"""Generates textured-Black hair styles as proxies fitted to the body scalp.

Asked for by the owner: afro (the owner's word is `bambucha`), and later locs,
cornrows and bantu knots. ATTEMPTED 2026-09-11 and not shipped -- five
iterations produced silhouettes too crude to carry the names. `memory/todo.md`
records why, and every number below is measured rather than guessed.

WHAT WENT WRONG LAST TIME, and what is different now:

* Placement raycast from the head centre onto the scalp. The scalp is not a
  closed dome, so a direction grid misses, and the nearest-direction fallback
  silently piled every miss onto the rim. THIS generator never searches for a
  scalp point: it starts from the scalp VERTICES themselves and pushes them
  outward, so there is nothing to miss.
* `helper-hair` was the obvious source and is the wrong one -- it is a long-hair
  envelope carrying ribbons down over the face. The region here is the BODY
  group only.

THE FIT. `fitProxy` (src/core/Proxy.cpp:423-441) computes
    P = SUM w_k * H[v_k] + (m.x*d.x, m.y*d.y, m.z*d.z)
and `TMatrix::diagonal` (src/core/Proxy.cpp:82-84) returns (1,1,1) when the
file declares no scale or shear form -- which this one does not. So `d` is a
plain WORLD-SPACE offset in rest, and a proxy vertex is written as
    <b> <b> <b> 1 0 0 <dx> <dy> <dz>
binding to base vertex b. Rest space is right: fitting runs before skinning
(main.cpp wornSkins), so hair anchored to the scalp follows a head turn free.
"""
import argparse
import collections
import math
import random
import sys
import uuid
from pathlib import Path
from typing import NamedTuple

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT / "data" / "3dobjs" / "base.obj"
OUT = ROOT / "data" / "hair"
# Everything this writes lands in `data/hair`, which IS the shipped asset tree:
# `AssetIndex::build` scans it, so a style written there is a wearable the moment
# it exists, and the asset-index test counts it. That is why the generator ships
# only styles that have been rendered and looked at -- an unfinished one dropped
# here once turned that test red on a working copy that had merely RUN this.

BANNER = "# Generated by tools/make_hair_styles.py -- do not edit by hand."

# The swept styles wear a SEVEN-strand sheet, not the scalp's 52. A tube is six
# or seven facets around, so 52 strands is about eight per facet and aliases
# into stipple -- rendered, cornrows nearly vanished and the knots speckled.
# Shells and cards have many samples across `u` and want the dense sheet.
TUBE_MATERIAL = "materials/hair_tube.mhmat"

# The cranium centre, measured and recorded in `memory/todo.md`.
CENTRE = (0.0, 7.75, 0.50)

# The hairline, in degrees of elevation about CENTRE, as a function of azimuth
# measured from the FRONT (+z). Measured on the base mesh: forehead sits at
# ~+9 degrees in this frame, brow -13, ears -25, nape -50. An earlier attempt
# used `14 + 20*cos(theta)` in a frame 0.2 dm too low and put every style in a
# band across the crown that read as a headband.
def hairline(azim_deg: float) -> float:
    """MIRRORS `mh::core::hairlineElevation`. `hairline_matches_app` gates it."""
    c = math.cos(math.radians(azim_deg))
    return -23.0 + 29.5 * c + 2.5 * c * c


def read_base():
    verts, faces = [], []
    group = ""
    for line in BASE.read_text().splitlines():
        if line.startswith("v "):
            verts.append(tuple(float(t) for t in line.split()[1:4]))
        elif line.startswith("g "):
            group = line.split(None, 1)[1].strip()
        elif line.startswith("f ") and group == "body":
            faces.append([int(p.split("/")[0]) - 1 for p in line.split()[1:]])
    return verts, faces


def spherical(v):
    """Elevation and azimuth of a vertex about CENTRE, in degrees."""
    dx, dy, dz = v[0] - CENTRE[0], v[1] - CENTRE[1], v[2] - CENTRE[2]
    return (math.degrees(math.atan2(dy, math.hypot(dx, dz))),
            math.degrees(math.atan2(dx, dz)))








def write_bound_style(name, stem, points, faces, bindings, uvs=None,
                      material="materials/hair.mhmat", uuid_override=""):
    """A style whose geometry is AUTHORED, not cut from the base mesh.

    The .obj carries the authored positions and the .mhclo carries one binding
    per vertex, in the same order -- which is the contract `fitProxy` reads.
    """
    obj = [BANNER,
           f"# {name}: {len(points)} vertices, {len(faces)} faces.", "g " + stem]
    for x, y, z in points:
        obj.append(f"v {x:.6f} {y:.6f} {z:.6f}")
    # UVs, WITHOUT WHICH A STRAND TEXTURE HAS NOWHERE TO GO. The four generated
    # styles shipped with no `vt` at all, so `materials/hair.mhmat`'s own note
    # -- "needs an alpha-cut strand texture, which the cage geometry cannot
    # stand in for" -- described a thing that could not be wired up even if the
    # texture existed. MEASURED on the export: body 14,517 distinct UVs, eyes
    # 808, teeth 136, hair ZERO.
    #
    # One `vt` per vertex, in vertex order, so a face corner is `v/vt` with the
    # same index twice. That is what the sweeps produce -- u around the tube, v
    # along it -- and it keeps the .obj readable beside the .mhclo, whose
    # bindings are also one per vertex in the same order.
    if uvs and len(uvs) == len(points):
        for u, v in uvs:
            obj.append(f"vt {u:.6f} {v:.6f}")
        for f in faces:
            obj.append("f " + " ".join(f"{i + 1}/{i + 1}" for i in f))
    elif uvs:
        # REFUSED, not reported. This printed to stderr, wrote the .obj with no
        # `vt` and returned success -- and `make_eyebrows.py`, which had a copy
        # of the same shape, is exactly how a slot sat at zero uvs through
        # every run that "worked". Four callers go through this one (coils,
        # cornrows, locs, bantu), so the guard belongs here rather than in the
        # single path that happened to get debugged.
        raise SystemExit(
            f"{stem}: {len(uvs)} uvs for {len(points)} vertices -- refusing to "
            f"write a mesh that cannot carry its strand alpha"
        )
    else:
        for f in faces:
            obj.append("f " + " ".join(str(i + 1) for i in f))
    mhclo = [
        BANNER,
        "#",
        "# AUTHORED geometry bound to the body scalp by three base vertices,",
        "# barycentric weights and an offset -- `mh::core::bindToSurface` via",
        "# `--bind-points`. The scalp is only ten vertices across, so rows this",
        "# fine cannot be cut from base vertices.",
        f"name {name}",
        # A REAL uuid, unlike the `8f2c1d4a-hair-<stem>` placeholder the shipped
        # afro still carries: `AssetIndex::findByUuid` is how a saved model
        # names its proxy, so a style that ships with a malformed one can never
        # be reloaded. The afro's is left alone deliberately -- changing an
        # asset's identity orphans every .mhm that already references it, and
        # that is a migration, not a generator fix.
        #
        # `uuid_override` EXISTS FOR THAT SENTENCE. When the afro moved from
        # `write_style` to this function, it silently picked up a uuid5 here
        # and its identity changed from `8f2c1d4a-hair-afro` -- performing by
        # accident the migration the paragraph above refuses to perform on
        # purpose. Every .mhm saved with an afro would have loaded bald. The
        # afro now passes its old id through; a NEW style has no saved models
        # to orphan and gets a real one.
        f"uuid {uuid_override or uuid.uuid5(uuid.NAMESPACE_URL, 'makehuman/hair/' + stem)}",
        "basemesh hm08",
        f"obj_file {stem}.obj",
        f"material {material}",
        "z_depth 60",
        "verts 0",
    ]
    mhclo.extend(bindings)
    return "\n".join(obj) + "\n", "\n".join(mhclo) + "\n"


def hairline_matches_app(verts, faces, app_path="") -> int:
    """0 if this generator's hairline is the SAME hairline the application walks.

    `mh::core::hairBearingScalp` holds the formula in C++ now, because a braid
    is routed over the region by `pathOverSurface` before any style exists. Two
    copies of a formula drift silently, and the drift would show as an afro
    whose rim sits where no cornrow can start -- so compare the REGIONS, not the
    constants, and let the application be the authority on its own.
    """
    try:
        app = app_binary(app_path)
        theirs = {int(line.split()[0])
                  for line in subprocess.run([app, "--spread-roots", "999"],
                                             capture_output=True, text=True,
                                             check=True).stdout.splitlines()
                  if line.strip()}
    except (subprocess.CalledProcessError, FileNotFoundError) as exc:
        # A MISSING or failing application is not a failure of THIS comparison,
        # which is about the hairline formula rather than about the styles.
        # Unreachable from `--check` since cornrows began shipping -- `derive()`
        # hard-fails on a missing application first -- but this is also called
        # from a plain run, where the afro alone is still derivable.
        print(f"hairline: need the built application to compare ({exc}) -- skipped",
              file=sys.stderr)
        return 0
    except (ValueError, IndexError) as exc:
        # Output that is not "index x y z" is a DIFFERENT thing: the application
        # ran and answered something this cannot read. Skipping would let a
        # broken binary read as a pass, and letting the ValueError escape would
        # report it as a crash rather than as a diagnosis.
        print(f"hairline: the application answered something unreadable ({exc})",
              file=sys.stderr)
        return 1
    body = set()
    for f in faces:
        body.update(f)
    ours = {v for v in body
            if spherical(verts[v])[0] >= hairline(spherical(verts[v])[1])}
    if ours != theirs:
        print(f"hairline: this generator selects {len(ours)} scalp vertices, the "
              f"application {len(theirs)}; {len(ours ^ theirs)} differ", file=sys.stderr)
        return 1
    print(f"hairline: {len(ours)} scalp vertices, same set as the application")
    return 0


def derive(verts, faces, app_path=""):
    """Every shipped style, as {filename: text}.

    Cornrows need the application -- it owns the scalp region and the
    barycentric binder -- so this raises rather than returning a short dict if
    it cannot be run. A generator that silently ships fewer styles than it
    claims is exactly the failure `--check` exists to catch.
    """
    # NO STYLE IN THIS TREE IS A SHELL ANY MORE. The afro went first -- one
    # offset copy of the scalp with the hair painted on by an alpha, and no
    # texture makes a shell read as hair close up, because the geometry has no
    # hairs in it. The skullcaps under the rope styles and the bantu knots were
    # the last two, and they are grown from coiled cards now as well.
    #
    # `afro()`, `write_style()` and `cap_uvs()` went WITH them. They had been
    # kept as "the reference for how a shell is cut from the body mesh if a
    # shell style is ever wanted again" -- 156 lines with no caller, retained
    # against a need nobody has. Git remembers them; this file does not need to.
    wanted = {}

    pts, fs, rows, app, cuvs = cornrows(verts, faces, app_path)
    # `len(binds) == len(pts)` alone is satisfied by 0 == 0. If every row failed
    # to trace, that wrote an EMPTY cornrows.obj into `data/hair`, which
    # `loadObj` rejects -- and a rejected proxy renders as a bald head rather
    # than as an error. So the row count is checked too.
    if rows != CORNROW_ROWS:
        raise RuntimeError(f"{rows} of {CORNROW_ROWS} cornrows traced")
    binds = bind_points(app, pts)
    if not pts or len(binds) != len(pts):
        raise RuntimeError(f"{len(binds)} bindings for {len(pts)} cornrow points")
    cobj, cmhclo = write_bound_style("Cornrows", "cornrows", pts, fs, binds, cuvs,
                                      material=TUBE_MATERIAL)
    wanted["cornrows.obj"] = cobj
    wanted["cornrows.mhclo"] = cmhclo

    bpts, bfs, roots, _, cap_binds, ncap, buvs = bantu(verts, faces, app_path)
    # Only the KNOT points go to the binder; the cap already carries its own
    # bindings, one per base vertex it grew from.
    bbinds = cap_binds + bind_points(app, bpts[ncap:])
    if len(bbinds) != len(bpts):
        raise RuntimeError(f"{len(bbinds)} bindings for {len(bpts)} bantu points")
    bobj, bmhclo = write_bound_style("Bantu knots", "bantu_knots", bpts, bfs, bbinds, buvs,
                                      material=TUBE_MATERIAL)
    wanted["bantu_knots.obj"] = bobj
    wanted["bantu_knots.mhclo"] = bmhclo

    # BOTH ROPE STYLES, from one generator. Locs and dreadlocks differ only in
    # the `RopeStyle` block, so writing them in a loop is what keeps a fix to
    # the hang or the shelf rule from reaching one and missing the other.
    ropes = {}
    for spec in (LOCS, DREADS):
        lpts, lfs, lroots, _, lshort, lcap, lncap, luvs = locs(verts, faces, app_path, spec)
        # A rope of two rings is not a loc. The failure this names is real and
        # was MEASURED: before `LOC_SCALP_BOTTOM` existed the crown apex read as
        # a shelf and EVERY rope stopped at ZERO steps. Observed range with the
        # style as it ships is 7..26, so the bar sits between the disaster and
        # the shortest real rope. It was 8 while I was guessing, which is one
        # step below nothing -- crossing-stacking then shortened one rope to 7
        # and tripped it.
        if lshort < 5:
            raise RuntimeError(f"the shortest {spec.stem} rope is {lshort} steps")
        # Only the ROPE points go to the binder; the cap already carries its own
        # bindings, one per base vertex it grew from.
        lbinds = lcap + bind_points(app, lpts[lncap:])
        if not lpts or len(lbinds) != len(lpts):
            raise RuntimeError(f"{len(lbinds)} bindings for {len(lpts)} {spec.stem} points")
        lobj, lmhclo = write_bound_style(spec.name, spec.stem, lpts, lfs, lbinds, luvs,
                                         material=TUBE_MATERIAL)
        wanted[f"{spec.stem}.obj"] = lobj
        wanted[f"{spec.stem}.mhclo"] = lmhclo
        ropes[spec.stem] = (len(lpts), len(lfs), len(lroots), lshort)

    summary = (f"cornrows: {len(pts)} vertices, {len(fs)} faces\n"
               + "".join(f"{k}: {v[0]} vertices, {v[1]} faces, {v[2]} ropes, "
                         f"shortest {v[3]} steps\n" for k, v in ropes.items())
               + (
               f"bantu knots: {len(bpts)} vertices, {len(bfs)} faces, "
               f"{len(roots)} roots, closest pair "
               f"{min(math.dist(a, b) for i, a in enumerate(roots) for b in roots[i + 1:]):.4f} dm"))
    return wanted, summary


def check(verts, faces, wanted, app_path="") -> int:
    """"Generated" is a claim LICENSING.md makes about these files, and without
    a gate it is an aspiration -- a hand-edit would go unnoticed for ever.

    The AFRO is no longer among them: it is grown by `tools/make_coils.py` and
    gated by that tool's own `--check`.
    """
    stale = [n for n, text in wanted.items()
             if not (OUT / n).exists() or (OUT / n).read_text() != text]
    for n in stale:
        print(f"{n} differs from a fresh derivation", file=sys.stderr)
    if stale:
        return 1
    print(f"hair: {len(wanted)} files match a fresh derivation")
    return hairline_matches_app(verts, faces, app_path)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="compare the committed assets against a fresh derivation and "
                         "fail if they differ, instead of writing them")
    ap.add_argument("--app", default="",
                    help="the built application to route and bind with; the caller passes "
                         "its own preset's binary rather than letting this guess")
    args = ap.parse_args()

    verts, faces = read_base()
    try:
        wanted, summary = derive(verts, faces, args.app)
    except (subprocess.CalledProcessError, FileNotFoundError, RuntimeError,
            ValueError, IndexError) as exc:
        # NOT a skip. Cornrows ship from `data/hair`, so a run that cannot
        # derive them cannot confirm them either, and saying so beats a green
        # line that covered half the styles.
        #
        # ValueError/IndexError are in the tuple for the same reason: the region
        # is parsed out of the application's stdout with `int(line.split()[0])`,
        # so one stray warning line would turn a diagnosable failure into a
        # traceback -- a CRASHED test rather than a red one with a reason.
        # `hairline_matches_app` already guarded exactly this; the cornrow path
        # had dropped the guard.
        print(f"cannot derive the hair styles without the application: {exc}", file=sys.stderr)
        return 2

    if args.check:
        return check(verts, faces, wanted, args.app)

    for n, text in wanted.items():
        (OUT / n).write_text(text)
    print(summary)
    return 0





